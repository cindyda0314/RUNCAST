/* 위경도 → 기상청 격자 (공식 변환식) */
function toGrid(lat, lon){
  const D = Math.PI/180, RE = 6371.00877/5.0;
  const slat1 = 30*D, slat2 = 60*D, olon = 126*D, olat = 38*D;
  let sn = Math.tan(Math.PI*0.25 + slat2*0.5) / Math.tan(Math.PI*0.25 + slat1*0.5);
  sn = Math.log(Math.cos(slat1)/Math.cos(slat2)) / Math.log(sn);
  let sf = Math.pow(Math.tan(Math.PI*0.25 + slat1*0.5), sn) * Math.cos(slat1) / sn;
  let ro = RE*sf / Math.pow(Math.tan(Math.PI*0.25 + olat*0.5), sn);
  let ra = RE*sf / Math.pow(Math.tan(Math.PI*0.25 + lat*D*0.5), sn);
  let th = lon*D - olon;
  if (th > Math.PI) th -= 2*Math.PI;
  if (th < -Math.PI) th += 2*Math.PI;
  th *= sn;
  return {nx: Math.floor(ra*Math.sin(th) + 43 + 0.5), ny: Math.floor(ro - ra*Math.cos(th) + 136 + 0.5)};
}

/* 선택용 헬퍼 */
function getRegion(sidoName, name){
  const s = REGIONS.find(r => r.sido === sidoName); if (!s) return null;
  const d = s.list.find(x => x[0] === name); if (!d) return null;
  return {sido: s.sido, short: s.short, name: d[0], lat: d[1], lon: d[2], ...toGrid(d[1], d[2])};
}
